/* eslint-disable import/no-unresolved, sonarjs/no-clear-text-protocols */
import { afterEach, beforeEach, describe, expect, mock, test } from "bun:test";

import {
	claimPrivateMobileConnect,
	buildPrivateConnectUrlFromParams,
	DEV_PRIVATE_BACKEND_URL,
	DEFAULT_PRIVATE_BACKEND_URL,
	RELEASE_PRIVATE_BACKEND_URL,
	parsePrivateConnectInput,
	parsePrivateMobileConnectLink,
} from "./private-mobile-connect";

const originalFetch = globalThis.fetch;

describe("private mobile connect helpers", () => {
	beforeEach(() => {
		globalThis.fetch = originalFetch;
	});

	afterEach(() => {
		globalThis.fetch = originalFetch;
	});

	test("parses a universal link into a mobile connect claim input", () => {
		expect(
			parsePrivateMobileConnectLink(
				"https://qr.remotecode.dev/connect/mcs_1/secret",
			),
		).toEqual({
			backendUrl: DEFAULT_PRIVATE_BACKEND_URL,
			code: "secret",
			sessionId: "mcs_1",
		});
	});

	test("accepts the legacy query-string connect link during rollout and keeps a trusted release backend", () => {
		expect(
			parsePrivateMobileConnectLink(
				"https://qr.remotecode.dev/connect?backendUrl=https%3A%2F%2Fprivate.remotecode.io%3A8787&sessionId=mcs_1&token=secret",
			),
		).toEqual({
			backendUrl: RELEASE_PRIVATE_BACKEND_URL,
			code: "secret",
			sessionId: "mcs_1",
		});
	});

test("normalizes local backend overrides in links to the release backend", () => {
	expect(
		parsePrivateMobileConnectLink(
			"https://qr.remotecode.dev/connect?backendUrl=http%3A%2F%2F127.0.0.1%3A8787&sessionId=mcs_1&token=secret",
		),
	).toEqual({
		backendUrl: RELEASE_PRIVATE_BACKEND_URL,
		code: "secret",
		sessionId: "mcs_1",
	});
});

	test("falls back to the default backend url when the legacy link omits it", () => {
		expect(
			parsePrivateMobileConnectLink("https://qr.remotecode.dev/connect?sessionId=mcs_1&token=secret"),
		).toEqual({
			backendUrl: DEFAULT_PRIVATE_BACKEND_URL,
			code: "secret",
			sessionId: "mcs_1",
		});
	});

	test("parses the app deep-link fallback generated by the QR landing page", () => {
		expect(
			parsePrivateMobileConnectLink("remotecode://connect/mcs_1/secret"),
		).toEqual({
			backendUrl: DEFAULT_PRIVATE_BACKEND_URL,
			code: "secret",
			sessionId: "mcs_1",
		});
		expect(
			parsePrivateMobileConnectLink("remotecode-mobile://connect/mcs_2/secret-2"),
		).toEqual({
			backendUrl: DEFAULT_PRIVATE_BACKEND_URL,
			code: "secret-2",
			sessionId: "mcs_2",
		});
	});

	test("round-trips encoded deep-link params through the native scheme", () => {
	const deepLink = buildPrivateConnectUrlFromParams({
		backendUrl: DEV_PRIVATE_BACKEND_URL,
		code: "secret code",
		sessionId: "mcs/special",
	});
	expect(deepLink).toBe("remotecode://connect/mcs%2Fspecial/secret%20code?backendUrl=https%3A%2F%2Fprivate.remotecode.io%3A8787");
	expect(parsePrivateMobileConnectLink(deepLink!)).toEqual({
		backendUrl: RELEASE_PRIVATE_BACKEND_URL,
		code: "secret code",
		sessionId: "mcs/special",
	});
});

	test("uses the QR payload backend when the embedded link omits it", () => {
	expect(
		parsePrivateConnectInput(JSON.stringify({
			backendUrl: DEV_PRIVATE_BACKEND_URL,
				connectorId: "con_1",
				connectorName: "Desktop Connector",
				linkUrl: "https://qr.remotecode.dev/connect/mcs_1/secret",
				type: "remotecode_private_mobile_connect",
				version: 1,
			})),
	).toEqual({
		claim: {
			backendUrl: RELEASE_PRIVATE_BACKEND_URL,
			code: "secret",
			sessionId: "mcs_1",
		},
			kind: "claim",
			rawValue: "https://qr.remotecode.dev/connect/mcs_1/secret",
		});
	});

	test("detects claim urls before legacy QR payloads", () => {
		const result = parsePrivateConnectInput(
			"https://qr.remotecode.dev/connect/mcs_1/secret",
		);
		expect(result.kind).toBe("claim");
		if (result.kind !== "claim") {
			throw new Error("claim_intent_expected");
		}
		expect(result.claim.sessionId).toBe("mcs_1");
	});

	test("rejects insecure http universal links", () => {
		const insecureUrl = "http://qr.remotecode.dev/connect/mcs_1/secret";
		expect(() =>
			parsePrivateMobileConnectLink(
				insecureUrl,
			),
		).toThrow("invalid_private_mobile_connect_link");
	});

	test("rejects legacy URL payloads from untrusted origins", () => {
		expect(() =>
			parsePrivateConnectInput(
				"https://evil.example.com/connect?connectorId=con_1&connectorName=MacBook",
			),
		).toThrow("invalid_private_mobile_connect_link");
	});

	test("claims a private mobile connect session through the private backend", async () => {
		const seenRequests: { body: string | null; url: string }[] = [];

		globalThis.fetch = mock(async (input: string | URL | Request, init?: RequestInit) => {
			seenRequests.push({
				body: typeof init?.body === "string" ? init.body : null,
				url: String(input),
			});

			return new Response(JSON.stringify({
				backendUrl: RELEASE_PRIVATE_BACKEND_URL,
				connector: {
					id: "con_1",
					name: "Studio MacBook",
				},
				session: {
					accessToken: "access-token",
					refreshToken: "access-token",
					user: {
						daysRemaing: 30,
						daysRemaining: 30,
						email: "dev@example.com",
						id: "usr_1",
						subscribed: true,
					},
				},
			}), {
				headers: { "content-type": "application/json" },
				status: 200,
			});
		}) as unknown as typeof fetch;

		const claim = await claimPrivateMobileConnect({
			link: {
				backendUrl: RELEASE_PRIVATE_BACKEND_URL,
				code: "secret",
				sessionId: "mcs_1",
			},
		});

		expect(claim.connector.id).toBe("con_1");
		expect(seenRequests).toEqual([
			{
				body: JSON.stringify({
					code: "secret",
					sessionId: "mcs_1",
				}),
				url: "https://private.remotecode.io:8787/v1/private/mobile-connect/claim",
			},
		]);
	});
});
