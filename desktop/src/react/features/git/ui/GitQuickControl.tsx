import { ArrowUp, Check, Circle, GitBranch, Loader2, Minus, Plus, X } from "lucide-react";
import { type FormEvent, useCallback, useEffect, useState } from "react";

import { Badge } from "../../../components/ui/badge";
import { Button } from "../../../components/ui/button";
import { cn } from "../../../lib/utils";
import type { CommitProjectRequestDTO, GitStatusDTO, ProjectDTO } from "../../../shared/api/remotecode-http";

interface GitClient {
	getProjectGitStatus: (projectId: string) => Promise<GitStatusDTO>;
	commitProject: (
		projectId: string,
		input: CommitProjectRequestDTO,
	) => Promise<{
		commit: {
			branch: string | null;
			commitHash: string | null;
			commitMessage: string;
			pushed: boolean;
			pushedWithUpstream: boolean;
		};
	}>;
}

type GitCommitResult = Awaited<ReturnType<GitClient["commitProject"]>>["commit"];

interface GitQuickControlProps {
	client: GitClient;
	project: Pick<ProjectDTO, "id" | "name" | "path"> | null;
	disabled?: boolean;
	className?: string;
	onCommitted?: (commit: GitCommitResult) => void;
}

interface SuccessToast {
	title: string;
	description: string;
}

const toCommitButtonLabel = (added: number, removed: number): string => `+${added} / -${removed}`;
const hasText = (value: string): boolean => value.trim().length > 0;

const toAutogeneratedCommitMessage = (status: GitStatusDTO | null): string => {
	if (!status || status.changedFiles <= 0) {
		return "Update project files";
	}

	if (status.added > 0 || status.removed > 0) {
		const details = [`+${status.added}`, `-${status.removed}`].join(" ");
		return `Update project files (${details})`;
	}

	return status.changedFiles === 1 ? "Update 1 file" : `Update ${status.changedFiles} files`;
};

const toCommitSuccessToast = (commit: GitCommitResult): SuccessToast => {
	const title = commit.pushed ? "Commit and push completed" : "Commit completed";
	const action = commit.pushed ? "committed and pushed" : "committed";
	const branchSuffix = commit.branch ? ` on ${commit.branch}` : "";

	return {
		title,
		description: `Your changes were ${action}${branchSuffix}.`,
	};
};

type CommitAction = "commit" | "push";

export const GitQuickControl = ({
	client,
	className,
	disabled = false,
	project,
	onCommitted,
}: GitQuickControlProps): JSX.Element => {
	const projectId = project?.id ?? null;

	const [isPanelOpen, setIsPanelOpen] = useState(false);
	const [status, setStatus] = useState<GitStatusDTO | null>(null);
	const [isLoadingStatus, setIsLoadingStatus] = useState(false);
	const [statusError, setStatusError] = useState<string | null>(null);
	const [commitMessage, setCommitMessage] = useState("");
	const [includeUnstaged, setIncludeUnstaged] = useState(true);
	const [nextAction, setNextAction] = useState<CommitAction>("commit");
	const [isCommitting, setIsCommitting] = useState(false);
	const [activeCommitAction, setActiveCommitAction] = useState<CommitAction | null>(null);
	const [activeCommitBranch, setActiveCommitBranch] = useState<string | null>(null);
	const [actionError, setActionError] = useState<string | null>(null);
	const [successToast, setSuccessToast] = useState<SuccessToast | null>(null);

	const isRepo = status?.isRepo === true;
	const hasStatus = status !== null;
	const isBusy = isLoadingStatus || isCommitting;
	const changedCount = status ? status.changedFiles : 0;
	const canCommit = isRepo && changedCount > 0 && !isBusy && !disabled;
	const isControlBusy = isBusy || (hasStatus && !isRepo);
	const addedCount = isRepo ? status.added : 0;
	const removedCount = isRepo ? status.removed : 0;

	const clearCommitState = useCallback(() => {
		setCommitMessage("");
		setIncludeUnstaged(true);
		setNextAction("push");
	}, []);

	const resetCommitProgress = useCallback(() => {
		setActiveCommitAction(null);
		setActiveCommitBranch(null);
	}, []);

	const resetTransientState = useCallback(() => {
		setStatus(null);
		setStatusError(null);
		setActionError(null);
		clearCommitState();
	}, [clearCommitState]);

	const fetchStatus = useCallback(async () => {
		if (!projectId) {
			resetTransientState();
			return;
		}

		setStatusError(null);
		setActionError(null);
		setIsLoadingStatus(true);

		try {
			const next = await client.getProjectGitStatus(projectId);
			setStatus(next);
			if (!next.isRepo) {
				clearCommitState();
			}
		} catch (error: unknown) {
			resetTransientState();
			setStatusError(error instanceof Error ? error.message : "Unable to load git status");
		} finally {
			setIsLoadingStatus(false);
		}
	}, [clearCommitState, client, projectId, resetTransientState]);

	const closePanel = useCallback(() => {
		if (isCommitting) {
			return;
		}

		setIsPanelOpen(false);
		setStatusError(null);
		setActionError(null);
		clearCommitState();
	}, [clearCommitState, isCommitting]);

	const runCommit = useCallback(
		async (action: CommitAction) => {
			if (!projectId || !canCommit) {
				return;
			}

			setActionError(null);
			setActiveCommitAction(action);
			setActiveCommitBranch(status?.currentBranch ?? null);
			setIsCommitting(true);

			try {
				const message = hasText(commitMessage) ? commitMessage.trim() : toAutogeneratedCommitMessage(status);
				const response = await client.commitProject(projectId, {
					message,
					includeUnstaged,
					push: action === "push",
				});

				onCommitted?.(response.commit);
				setSuccessToast(toCommitSuccessToast(response.commit));
				clearCommitState();
				await fetchStatus();
				setIsPanelOpen(false);
			} catch (error: unknown) {
				setActionError(error instanceof Error ? error.message : "Unable to create commit");
			} finally {
				setIsCommitting(false);
				resetCommitProgress();
			}
		},
		[
			canCommit,
			commitMessage,
			clearCommitState,
			client,
			fetchStatus,
			includeUnstaged,
			onCommitted,
			projectId,
			resetCommitProgress,
			status,
		],
	);

	const handleContinue = useCallback(
		(event: FormEvent<HTMLFormElement>) => {
			event.preventDefault();
			if (!canCommit) {
				return;
			}
			void runCommit(nextAction);
		},
		[canCommit, nextAction, runCommit],
	);

	const handleTogglePanel = useCallback(() => {
		if (!projectId || disabled || isLoadingStatus || isCommitting) {
			return;
		}

		setActionError(null);
		setIsPanelOpen((current) => {
			const next = !current;
			if (next) {
				setIncludeUnstaged(true);
				setNextAction("push");
			}
			return next;
		});
	}, [disabled, isCommitting, isLoadingStatus, projectId]);

	useEffect(() => {
		if (!isPanelOpen || isCommitting) {
			return;
		}

		const handleEscape = (event: KeyboardEvent) => {
			if (event.key === "Escape") {
				closePanel();
			}
		};

		window.addEventListener("keydown", handleEscape);
		return () => {
			window.removeEventListener("keydown", handleEscape);
		};
	}, [closePanel, isCommitting, isPanelOpen]);

	useEffect(() => {
		if (!successToast) {
			return;
		}

		const timeoutId = window.setTimeout(() => {
			setSuccessToast(null);
		}, 3200);

		return () => {
			window.clearTimeout(timeoutId);
		};
	}, [successToast]);

	useEffect(() => {
		if (!projectId || disabled) {
			setIsPanelOpen(false);
			resetTransientState();
			return;
		}

		void fetchStatus();
	}, [disabled, fetchStatus, projectId, resetTransientState]);

	const commitProgressDetail =
		activeCommitAction === "push"
			? `Pushing to branch ${activeCommitBranch ?? "current"}`
			: `Updating branch ${activeCommitBranch ?? "current"}`;

	return (
		<div className={cn("relative inline-flex", className)}>
			<Button
				aria-label="Toggle Git quick control"
				className="h-8 px-2"
				disabled={isControlBusy || !projectId || disabled}
				onClick={handleTogglePanel}
				type="button"
				variant="outline"
			>
				<GitBranch className="h-3.5 w-3.5" />
				<span className="font-mono text-[11px]">{toCommitButtonLabel(addedCount, removedCount)}</span>
				<Badge className="h-5 rounded-full px-1.5 text-[10px] uppercase tracking-[0.11em] text-slate-100">Git</Badge>
			</Button>

			{isPanelOpen ? (
				<>
					<div
						aria-hidden="true"
						className="fixed inset-0 z-[88] bg-black/60 backdrop-blur-[1.5px]"
						onClick={closePanel}
					/>
					<div className="fixed inset-0 z-[89] grid place-items-center p-4">
						<div
							aria-label="Git quick commit modal"
							aria-modal="true"
							className="w-[380px] max-h-[calc(100vh-2rem)] max-w-[calc(100vw-1.75rem)] overflow-y-auto rounded-[18px] border border-[#363a42] bg-[radial-gradient(180%_130%_at_50%_0%,rgba(45,47,53,0.85)_0%,rgba(29,31,36,0.96)_55%,rgba(23,24,28,0.98)_100%)] px-5 pb-5 pt-4 shadow-[0_30px_72px_rgba(0,0,0,0.55)]"
							onClick={(event) => {
								event.stopPropagation();
							}}
							role="dialog"
						>
							<div className="flex items-center justify-between">
								<h3 className="text-[18px] font-semibold leading-6 tracking-[-0.01em] text-[#f4f6fa]">
									{isCommitting ? "Committing changes" : "Commit your changes"}
								</h3>
								<button
									aria-label="Close git quick commit modal"
									className={cn(
										"grid h-7 w-7 place-items-center rounded-md text-[#cfd3db] transition",
										isCommitting
											? "cursor-not-allowed opacity-55"
											: "hover:bg-white/[0.06] hover:text-white",
									)}
									disabled={isCommitting}
									onClick={closePanel}
									type="button"
								>
									<X className="h-4 w-4" />
								</button>
							</div>

							{isCommitting ? (
								<section className="mt-5 space-y-4">
									<p className="text-[14px] text-[#c4c9d1]">Hold tight, this may take a few moments...</p>
									<div className="rounded-2xl border border-white/10 bg-black/25 px-3 py-3">
										<div className="flex items-center gap-2 text-sm font-medium text-[#f2f5fa]">
											<Loader2 className="h-4 w-4 animate-spin" />
											<span>Committing changes</span>
										</div>
										<p className="pl-6 pt-1 text-[12px] text-[#afb4be]">{commitProgressDetail}</p>
									</div>
								</section>
							) : isLoadingStatus ? (
								<div className="mt-6 flex items-center gap-2 rounded-xl border border-white/10 bg-black/20 px-3 py-2 text-sm text-[#d7dbe2]">
									<Loader2 className="h-4 w-4 animate-spin" />
									<span>Loading git status...</span>
								</div>
							) : statusError ? (
								<div className="mt-6 rounded-xl border border-rose-300/30 bg-rose-500/10 px-3 py-2 text-sm text-rose-100">
									{statusError}
								</div>
							) : isRepo ? (
								<form className="mt-4 space-y-4" onSubmit={handleContinue}>
									<div className="space-y-2 text-sm text-[#f4f6fa]">
										<div className="flex items-center justify-between gap-4">
											<span className="font-semibold text-[#eceff4]">Branch</span>
											<div className="inline-flex min-w-0 items-center gap-2 text-right">
												<GitBranch className="h-4 w-4 shrink-0 text-[#d7dbe2]" />
												<span className="truncate text-[15px] font-medium text-[#f6f8fc]">
													{status.currentBranch ?? (status.isDetachedHead ? "Detached" : "Unknown")}
												</span>
											</div>
										</div>
										<div className="flex items-center justify-between gap-4">
											<span className="font-semibold text-[#eceff4]">Changes</span>
											<div className="inline-flex items-center gap-2 text-[15px] font-medium">
												<span className="text-[#aeb3bc]">
													{changedCount} {changedCount === 1 ? "file" : "files"}
												</span>
												<span className="inline-flex items-center gap-0.5 text-emerald-400">
													<Plus className="h-3.5 w-3.5" />
													{status.added}
												</span>
												<span className="inline-flex items-center gap-0.5 text-rose-400">
													<Minus className="h-3.5 w-3.5" />
													{status.removed}
												</span>
											</div>
										</div>
									</div>

									<label className="flex items-center gap-2.5 py-[4px] text-[14px] font-medium text-[#eceff4]">
										<button
											aria-label={includeUnstaged ? "Disable include unstaged changes" : "Enable include unstaged changes"}
											className={cn(
												"relative h-6 w-11 rounded-full border transition-colors",
												includeUnstaged ? "border-sky-300/80 bg-[#4ea8ff]" : "border-white/15 bg-[#2a2d33]",
											)}
											onClick={() => {
												setIncludeUnstaged((current) => !current);
											}}
											type="button"
										>
											<span
												className={cn(
													"absolute left-[2px] top-[2px] h-[20px] w-[20px] rounded-full bg-white shadow-[0_2px_6px_rgba(0,0,0,0.35)] transition-transform",
													includeUnstaged ? "translate-x-5" : "",
												)}
											/>
										</button>
										Include unstaged
									</label>

									<div className="space-y-2">
										<label className="block text-[13px] font-semibold text-[#eceff4]" htmlFor="git-quick-commit-message">
											Commit message
										</label>
										<input
											aria-label="Commit message"
											className="h-[44px] w-full rounded-xl border border-white/10 bg-black/20 px-3.5 text-[13px] text-[#f6f8fc] outline-none placeholder:text-[#8f949d] focus-visible:border-white/20"
											disabled={isBusy || !isRepo}
											id="git-quick-commit-message"
											onChange={(event) => {
												setCommitMessage(event.target.value);
											}}
											placeholder="Leave blank to autogenerate a commit message"
											value={commitMessage}
										/>
									</div>

									<div className="space-y-2">
										<p className="text-[13px] font-semibold text-[#eceff4]">Next steps</p>
										<div className="overflow-hidden rounded-2xl border border-white/10 bg-black/15">
											<button
												className={cn(
													"flex h-10 w-full items-center justify-between px-3 text-left text-[13px] transition-colors",
													nextAction === "commit" ? "bg-white/[0.03] text-[#f4f6fa]" : "text-[#d8dce3] hover:bg-white/[0.02]",
												)}
												onClick={() => {
													setNextAction("commit");
												}}
												type="button"
											>
												<span className="inline-flex items-center gap-2">
													<Circle className="h-3.5 w-3.5" />
													Commit
												</span>
												{nextAction === "commit" ? <Check className="h-4 w-4" /> : null}
											</button>
											<button
												className={cn(
													"flex h-10 w-full items-center justify-between border-t border-white/10 px-3 text-left text-[13px] transition-colors",
													nextAction === "push" ? "bg-white/[0.03] text-[#f4f6fa]" : "text-[#d8dce3] hover:bg-white/[0.02]",
												)}
												onClick={() => {
													setNextAction("push");
												}}
												type="button"
											>
												<span className="inline-flex items-center gap-2">
													<ArrowUp className="h-4 w-4" />
													Commit and push
												</span>
												{nextAction === "push" ? <Check className="h-4 w-4" /> : null}
											</button>
										</div>
									</div>

									<button
										className="mt-1 flex h-[40px] w-full items-center justify-center rounded-xl bg-[#f2f3f5] text-[14px] font-medium text-[#21242a] transition hover:bg-white disabled:cursor-not-allowed disabled:bg-white/20 disabled:text-[#9aa0a8]"
										disabled={!canCommit}
										type="submit"
									>
										Continue
									</button>

									{actionError ? (
										<p className="rounded-lg border border-rose-300/30 bg-rose-500/10 px-3 py-2 text-sm text-rose-100">
											{actionError}
										</p>
									) : null}
								</form>
							) : (
								<div className="mt-6 rounded-xl border border-white/10 bg-black/20 px-3 py-2 text-sm text-[#d7dbe2]">
									{status ? "This folder is not a git repository." : "No git status available yet."}
								</div>
							)}
						</div>
					</div>
				</>
			) : null}

			{successToast ? (
				<div className="pointer-events-none fixed right-4 top-4 z-[95] max-w-[min(360px,calc(100vw-2rem))]">
					<div className="rounded-xl border border-emerald-300/30 bg-emerald-950/90 px-3.5 py-3 shadow-[0_12px_32px_rgba(0,0,0,0.45)] backdrop-blur-sm">
						<p className="text-sm font-semibold text-emerald-100">{successToast.title}</p>
						<p className="mt-1 text-xs text-emerald-200/90">{successToast.description}</p>
					</div>
				</div>
			) : null}
		</div>
	);
};
